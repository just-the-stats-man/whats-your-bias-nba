source('scripts/load.R')
folder<-'data/processed/phase3';dir.create(folder,recursive=TRUE,showWarnings=FALSE)
con<-connect_warehouse()
tryCatch({
  DBI::dbExecute(con,'SET threads=4');DBI::dbExecute(con,"SET memory_limit='3GB'")
  checks<-rbind(warehouse_integrity_report(con),historical_integrity(con),execution_integrity(con))
  utils::write.csv(checks,file.path(folder,'baseline_integrity.csv'),row.names=FALSE)
  stopifnot(nrow(checks)==85L,all(checks$passed))
  checksum<-function(sql)DBI::dbGetQuery(con,paste0('SELECT count(*) n,CAST(bit_xor(hash(t)) AS VARCHAR) checksum FROM (',sql,') t'))
  paths<-list.files('data/processed/execution_parquet',pattern='[.]parquet$',full.names=TRUE)
  rows<-lapply(paths,function(path) {
    table<-sub('[.]parquet$','',basename(path))
    old<-checksum(paste0('SELECT * FROM read_parquet(',DBI::dbQuoteString(con,normalizePath(path,winslash='/')),')'))
    now<-checksum(paste0('SELECT * FROM ',DBI::dbQuoteIdentifier(con,table)))
    data.frame(table=table,rows=old$n,checksum=old$checksum,path=path,sha256=file_sha256(path),passed=identical(old,now))
  })
  snapshot<-do.call(rbind,rows)
  utils::write.csv(snapshot,file.path(folder,'phase2_baseline_tables.csv'),row.names=FALSE)
  stopifnot(nrow(snapshot)==36L,all(snapshot$passed))
  manifest<-DBI::dbReadTable(con,'datasets')
  manifest$actual_sha256<-vapply(manifest$raw_path,file_sha256,character(1))
  manifest$passed<-manifest$sha256==manifest$actual_sha256
  utils::write.csv(manifest,file.path(folder,'phase2_baseline_inputs.csv'),row.names=FALSE)
  stopifnot(nrow(manifest)==9645L,all(manifest$passed))
  saveRDS(list(commit='c391b10769c7898b6baf8abc2840631c3f878a0a',method=reconstruction_version,tables=snapshot,inputs=manifest,integrity=checks,verified_at=Sys.time()),file.path(folder,'phase2_baseline.rds'))
  cat('Phase 2 baseline: 85 integrity checks; 36 exact snapshot tables;',nrow(manifest),'input hashes passed\n')
},finally=DBI::dbDisconnect(con,shutdown=TRUE))
