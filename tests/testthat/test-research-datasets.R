withr::local_dir(Sys.getenv('WYB_ROOT'))
testthat::test_that('research views retain boxes and keep certification levels separate', {
  con<-connect_warehouse(':memory:');on.exit(DBI::dbDisconnect(con,shutdown=TRUE))
  ingest_bundle(con,readRDS('data/sample/bundle.rds'),'2024-25');import_reference(con,load_reference_fixture());reconcile_game_totals(con);reconstruct_season(con,'2024-25')
  install_research_views(con)
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_player_games')$n,DBI::dbGetQuery(con,'SELECT count(*) n FROM player_box_scores')$n)
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_shots')$n,0)
  testthat::expect_true(all(research_integrity(con)$passed))
  testthat::expect_gt(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_possession_stint_links')$n,0)
  testthat::expect_true(all(DBI::dbGetQuery(con,'SELECT duration_seconds FROM research_possession_stint_links')$duration_seconds>0))
  testthat::expect_gt(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_lineup_matchup_intervals')$n,0)
  time<-DBI::dbGetQuery(con,'SELECT game_id,sum(duration_seconds) AS covered_seconds FROM research_lineup_matchup_intervals GROUP BY game_id')
  testthat::expect_true(all(time$covered_seconds==2880))
  testthat::expect_error(research_tbl(con,'unlicensed_tracking'),'unavailable')
  id<-DBI::dbGetQuery(con,'SELECT min(game_id) id FROM games')$id
  DBI::dbExecute(con,"UPDATE reconstruction_status SET possessions_status='unresolved',lineups_status='unresolved' WHERE game_id=?",params=list(id))
  testthat::expect_gt(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_player_games WHERE game_id=?',params=list(id))$n,0)
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_possessions WHERE game_id=?',params=list(id))$n,0)
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM research_lineup_stints WHERE game_id=?',params=list(id))$n,0)
})
