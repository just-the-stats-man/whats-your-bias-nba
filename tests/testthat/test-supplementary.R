testthat::test_that('manual provider exports preserve declared grain, missing labels and permissions', {
  con<-connect_warehouse(':memory:');on.exit(DBI::dbDisconnect(con,shutdown=TRUE))
  path<-tempfile(fileext='.csv');on.exit(unlink(path),add=TRUE)
  utils::write.csv(data.frame(player_game=c('g:p','g:p'),distance_bucket=c('2-4 feet',''),attempts=c('2','0')),path,row.names=FALSE)
  permission<-list(approved=TRUE,local_retention=TRUE,receipt_id='test-only',terms_url='https://example.test/permission',modeling=FALSE)
  testthat::expect_error(ingest_authorized_export(con,path,'test','player_game_filter','player_game',NULL),'permission')
  rows<-ingest_authorized_export(con,path,'test','player_game_filter','player_game',permission)
  testthat::expect_true(all(rows$validation_status=='failed_validation_duplicate_source_key'))
  testthat::expect_true(grepl('"distance_bucket":""',rows$raw_record_json[2],fixed=TRUE))
  before<-DBI::dbReadTable(con,'supplementary_snapshots')
  ingest_authorized_export(con,path,'test','player_game_filter','player_game',permission)
  testthat::expect_identical(DBI::dbReadTable(con,'supplementary_snapshots'),before)
  testthat::expect_equal(nrow(DBI::dbReadTable(con,'supplementary_export_records')),2)
  testthat::expect_false(DBI::dbReadTable(con,'supplementary_permission_receipts')$modeling)
  testthat::expect_error(ingest_authorized_export(con,path,'test','shot_annotation','player_game',permission),'grain/key')
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM matchup_observations')$n,0)
})
