testthat::test_that('DunkAPI is opt-in, bounded, cached and secret-safe with mocked transport only', {
  folder<-tempfile();dir.create(folder);on.exit(unlink(folder,recursive=TRUE),add=TRUE)
  withr::local_envvar(DUNKAPI_API_KEY='synthetic-not-a-real-key')
  calls<-0L;mock<-function(url,key,params){calls<<-calls+1L;list(status=200L,body=as.character(jsonlite::toJSON(mock_dunk_payload(),auto_unbox=TRUE,null='null')))}
  testthat::expect_error(dunkapi_fetch('get_plays',list(game_id='123'),folder,transport=mock),'approval')
  testthat::expect_equal(calls,0L)
  a<-mock_dunk_approval();receipt<-dunkapi_fetch('get_plays',list(game_id='123'),folder,a,mock,wait=function(x)NULL)
  testthat::expect_false(receipt$live_validated);testthat::expect_equal(calls,1L)
  testthat::expect_equal(file_sha256(receipt$path),receipt$sha256)
  testthat::expect_false(any(grepl('synthetic-not-a-real-key',unlist(receipt),fixed=TRUE)))
  testthat::expect_identical(dunkapi_fetch('get_plays',list(game_id='123'),folder,transport=mock),receipt)
  testthat::expect_equal(calls,1L)
  dunkapi_fetch('get_plays',list(game_id='123',offset=2),folder,a,mock,wait=function(x)NULL)
  testthat::expect_error(dunkapi_fetch('get_plays',list(game_id='123',offset=4),folder,a,mock,wait=function(x)NULL),'cap exhausted')
  testthat::expect_equal(calls,2L)
  writeLines('{}',receipt$path)
  testthat::expect_error(dunkapi_fetch('get_plays',list(game_id='123'),folder,transport=mock),'hash mismatch')
})

testthat::test_that('DunkAPI schema, FT classes, duplicates and estimates remain separate from canonical facts', {
  payload<-mock_dunk_payload();rows<-normalize_dunkapi_plays(payload,'test-sha')
  testthat::expect_equal(rows$shot_class,c('field_goal','free_throw'))
  testthat::expect_true(all(is.na(rows$raw_x)));testthat::expect_equal(rows$model_status,c('estimated','source_missing'))
  testthat::expect_true(all(!rows$independent))
  bad<-payload;bad$count<-3;testthat::expect_error(normalize_dunkapi_plays(bad,'x'),'schema/count')
  bad<-payload;bad$plays[[2]]$seq<-1;testthat::expect_true(all(normalize_dunkapi_plays(bad,'x')$validation_status=='failed_validation'))
  bad<-payload;bad$plays[[2]]$shot$points_attempted<-3
