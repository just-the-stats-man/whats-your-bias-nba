  con<-connect_warehouse(':memory:');on.exit(DBI::dbDisconnect(con,shutdown=TRUE))
  path<-tempfile(fileext='.json');on.exit(unlink(path),add=TRUE);writeLines(as.character(jsonlite::toJSON(payload,auto_unbox=TRUE,null='null')),path)
  receipt<-list(provider='dunkapi',endpoint='get_plays',permission_status='approved_internal_use_no_raw_redistribution',path=path,sha256=file_sha256(path),request_hash='test',received_at=Sys.time(),schema_id='documented-offline-fixture',terms_url='https://dunkapi.com/terms',live_validated=FALSE)
  ingest_dunkapi_snapshot(con,receipt);ingest_dunkapi_snapshot(con,receipt)
