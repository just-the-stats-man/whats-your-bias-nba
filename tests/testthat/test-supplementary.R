testthat::test_that('failed requests do not leak keys or assume refunds', {
  folder<-tempfile();dir.create(folder);on.exit(unlink(folder,recursive=TRUE),add=TRUE)
  withr::local_envvar(DUNKAPI_API_KEY='synthetic-not-a-real-key')
  mock<-function(...)stop('synthetic-not-a-real-key')
  a<-mock_dunk_approval(10)
