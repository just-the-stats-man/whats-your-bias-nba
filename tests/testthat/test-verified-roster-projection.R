withr::local_dir(Sys.getenv('WYB_ROOT'))
testthat::test_that('missing NBA teams require recorded side plus verified roster and all statistics', {
  raw<-data.frame(source_row=1,gameId='22100001',personId='99',home='1',playerteamId=NA_character_,opponentteamId=NA_character_)
  counts<-c(fgm=2,fga=5,fg3m=1,fg3a=2,ftm=1,fta=1,points=6,assists=1,turnovers=1,rebounds=4,minutes=20)
  metrics<-historical_metrics();for(m in names(counts))raw[[metrics$source_column[match(m,metrics$metric)]]]<-as.character(counts[[m]])
  games<-data.frame(game_id='nba:0022100001',home_team_id='nba:1610612747',away_team_id='nba:1610612737')
  links<-data.frame(nba_game_id=games$game_id,espn_game_id='g')
  roster<-cbind(data.frame(game_id='g',player_id='espn:42',team_id='espn:13',did_not_play=FALSE),as.data.frame(as.list(counts)))
  players<-data.frame(nba_player_id='nba:99',player_id='espn:42');team<-utils::read.csv('config/team_crosswalk.csv',colClasses='character')
  recover<-function(r=raw,g=games,l=links,p=roster,ids=players)verified_roster_team_assignments(r,g,l,p,ids,team)
  good<-recover();testthat::expect_equal(nrow(good),1L);testthat::expect_equal(good$nba_team_id,games$home_team_id)
  testthat::expect_equal(good$source_row,1);testthat::expect_true(good$counts_match)
  bad<-raw;bad$home<-'unknown';testthat::expect_equal(nrow(recover(bad)),0L)
  bad<-raw;bad$home<-'0';testthat::expect_equal(nrow(recover(bad)),0L)
  bad<-raw;bad$points<-'7';testthat::expect_equal(nrow(recover(bad)),0L)
  bad<-raw;bad$numMinutes<-'23';testthat::expect_equal(nrow(recover(bad)),0L)
  bad<-raw;bad$opponentteamId<-'1610612737';testthat::expect_equal(nrow(recover(bad)),0L)
  testthat::expect_equal(nrow(recover(l=rbind(links,links))),0L)
  bad<-rbind(players,data.frame(nba_player_id='nba:100',player_id='espn:42'))
  testthat::expect_equal(nrow(recover(ids=bad)),0L)
})
