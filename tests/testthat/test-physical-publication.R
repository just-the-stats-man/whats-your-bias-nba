withr::local_dir(Sys.getenv('WYB_ROOT'))
testthat::test_that('physical publication preserves certified components, validates dependencies and resumes', {
  con<-connect_warehouse(':memory:');on.exit(DBI::dbDisconnect(con,shutdown=TRUE))
  ingest_bundle(con,readRDS('data/sample/bundle.rds'),'2024-25');import_reference(con,load_reference_fixture());reconcile_game_totals(con);reconstruct_season(con,'2024-25')
  id<-DBI::dbGetQuery(con,'SELECT min(game_id) id FROM games')$id
  other<-DBI::dbGetQuery(con,'SELECT * FROM possessions WHERE game_id!=? ORDER BY possession_id',params=list(id))
  DBI::dbExecute(con,'DELETE FROM lineup_players WHERE lineup_id IN (SELECT lineup_id FROM lineups WHERE game_id=?)',params=list(id))
  for(t in c('lineups','possessions','possession_events','non_possession_points'))DBI::dbExecute(con,paste0('DELETE FROM ',t,' WHERE game_id=?'),params=list(id))
  DBI::dbExecute(con,"UPDATE reconstruction_status SET possessions_status='unresolved',lineups_status='unresolved' WHERE game_id=?",params=list(id))
  x<-physical_recovery_inputs(con,id);a<-recovery_projection(x$e,x$p)
  r<-list(game=x$g,signature=digest::digest(unname(x),algo='sha256'),method=x$method,pos=reconstruct_possessions(a$e,x$g,a$p),lu=reconstruct_lineups(a$e,x$g,a$p),audit=a$audit)
  folder<-tempfile();dir.create(folder);on.exit(unlink(folder,recursive=TRUE),add=TRUE)
  path<-file.path(folder,'game.rds');saveRDS(r,path)
  index<-file.path(folder,'index.csv');row<-data.frame(game_id=id,method=r$method,path=path,sha256=file_sha256(path),possessions_before='unresolved',lineups_before='unresolved',possession_pass=TRUE,lineup_pass=TRUE)
  utils::write.csv(row,index,row.names=FALSE)
  testthat::expect_equal(unname(publish_physical_recovery(con,index,folder)),c(1L,1L))
  testthat::expect_equal(unname(publish_physical_recovery(con,index,folder)),c(0L,0L))
  testthat::expect_identical(DBI::dbGetQuery(con,'SELECT * FROM possessions WHERE game_id!=? ORDER BY possession_id',params=list(id)),other)
  testthat::expect_true(all(warehouse_integrity_report(con)$passed))
  testthat::expect_true(all(physical_recovery_integrity(con)$passed))
  testthat::expect_equal(DBI::dbGetQuery(con,'SELECT count(*) n FROM reconstruction_component_methods')$n,2)
  row$possessions_before<-'reconciled';row$possession_pass<-FALSE;utils::write.csv(row,index,row.names=FALSE)
  testthat::expect_error(publish_physical_recovery(con,index,folder),'regress')
})
